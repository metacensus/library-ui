// Writes ROUTES.md from the build: every page Astro emits, its audience and
// purpose from a JSON file of entries, and the links and forms in its built
// HTML. The build fails when a route has no entry, an entry has no route, or a
// page links where `deniedLinks` denies.
import { readFile, writeFile } from 'node:fs/promises'
import { URL, fileURLToPath } from 'node:url'

const ENTRIES = 'src/inventory/routes.json'
const OUTPUT = 'ROUTES.md'

/**
 * @param {object} [options]
 * @param {(hrefs: string[]) => string[]} [options.deniedLinks] The hrefs a page may not link to.
 * @returns {import("astro").AstroIntegration}
 */
export default function routeInventory({ deniedLinks = () => [] } = {}) {
  let base = '/'
  let root = new URL('file:///')
  return {
    name: 'route-inventory',
    hooks: {
      'astro:config:done': ({ config }) => {
        base = config.base.replace(/\/?$/, '/')
        root = config.root
      },
      'astro:build:done': async ({ dir, assets }) => {
        /** @type {Record<string, { audience: string, purpose: string }>} */
        const entries = JSON.parse(
          await readFile(new URL(ENTRIES, root), 'utf8'),
        )
        const patterns = [...assets.keys()].sort()
        const missing = patterns.filter((p) => !entries[p])
        const stale = Object.keys(entries).filter((p) => !assets.has(p))
        if (missing.length || stale.length) {
          throw new Error(
            `${ENTRIES} must name every route once: ` +
              `missing ${missing.join(', ') || 'none'}; ` +
              `no such route ${stale.join(', ') || 'none'}`,
          )
        }

        const dirPath = fileURLToPath(dir)
        const sections = []
        const denied = []
        for (const pattern of patterns) {
          const { audience, purpose } = entries[pattern]
          const lines = [
            `## \`${pattern}\``,
            '',
            `- Audience: ${audience}`,
            `- Purpose: ${purpose}`,
          ]
          for (const file of [...(assets.get(pattern) ?? [])].sort((a, b) =>
            a.href.localeCompare(b.href),
          )) {
            const path = fileURLToPath(file)
              .slice(dirPath.length)
              .replace(/(^|\/)index\.html$/, '$1')
            const html = await readFile(file, 'utf8')
            const links = linksIn(html)
            for (const href of deniedLinks(links)) {
              denied.push(`${base}${path} links ${href}`)
            }
            lines.push(
              `- \`${base}${path}\``,
              `  - Links: ${list(links)}`,
              `  - Forms: ${list(formsIn(html))}`,
            )
          }
          sections.push(lines.join('\n'))
        }
        if (denied.length) {
          throw new Error(
            `A page links where deniedLinks denies: ${denied.join('; ')}`,
          )
        }
        await writeFile(
          new URL(OUTPUT, root),
          `# Routes\n\nGenerated by the build from the built pages and ${ENTRIES}. Edit the entries, not this file.\n\n${sections.join('\n\n')}\n`,
        )
      },
    },
  }
}

/** @param {string[]} items */
const list = (items) =>
  items.length ? items.map((i) => `\`${i}\``).join(', ') : 'none'

/** @param {string} value */
const decode = (value) => value.replaceAll('&amp;', '&')

/** Every distinct `<a href>`, sorted. @param {string} html */
const linksIn = (html) =>
  [
    ...new Set(
      [...html.matchAll(/<a\b[^>]*?\shref="([^"]*)"/g)].map((m) =>
        decode(m[1]),
      ),
    ),
  ].sort()

/** Each `<form>` as its method, action and field names. @param {string} html */
const formsIn = (html) =>
  [...html.matchAll(/<form\b([^>]*)>([\s\S]*?)<\/form>/g)].map(
    ([, attrs, body]) => {
      const method = (
        /\smethod="([^"]*)"/.exec(attrs)?.[1] ?? 'get'
      ).toUpperCase()
      const action = /\saction="([^"]*)"/.exec(attrs)?.[1]
      const fields = [
        ...new Set(
          [
            ...body.matchAll(
              /<(?:input|select|textarea)\b[^>]*?\sname="([^"]*)"/g,
            ),
          ].map((m) => m[1]),
        ),
      ]
      return `${action ? `${method} ${decode(action)}` : 'no action'}: ${fields.join(' ')}`
    },
  )
